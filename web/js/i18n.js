/* Somali first, English second.
   Diiwaan is built for Somali businesses, so Somali is the default and English
   is the alternative — not the other way round. A missing Somali string falls
   back to English rather than showing a key, so a half-finished translation
   degrades into a readable page instead of a broken one. */

const KEY = 'diiwaan:lang';
export const LANGUAGES = [
  { id: 'so', name: 'Somali', native: 'Soomaali' },
  { id: 'en', name: 'English', native: 'English' }
];

const supported = id => LANGUAGES.some(l => l.id === id);

let current = (() => {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && supported(saved)) return saved;
  } catch { /* private mode */ }
  // Somali is the product's language, not a fallback for Somali devices. A phone
  // set to English still opens in Somali; choosing English is a decision the
  // person makes here, and it is remembered once they make it.
  return 'so';
})();

export const lang = () => current;

const listeners = new Set();
export const onLanguageChange = fn => { listeners.add(fn); return () => listeners.delete(fn); };

export function setLanguage(next) {
  if (!supported(next) || next === current) return current;
  current = next;
  try { localStorage.setItem(KEY, next); } catch { /* private mode */ }
  document.documentElement.lang = next;
  listeners.forEach(fn => fn(next));
  return current;
}

export const toggleLanguage = () => setLanguage(current === 'so' ? 'en' : 'so');

/** The other language, for a switch that says where it will take you. */
export const otherLanguage = () => LANGUAGES.find(l => l.id !== current);

/**
 * Looks up a key for the active language.
 * Values may carry {placeholders}, filled from `vars`.
 */
export function t(key, vars) {
  const table = DICT[current] || DICT.so;
  let value = table[key];
  if (value === undefined) value = DICT.en[key];
  if (value === undefined) return key;
  if (typeof value === 'function') return value(vars || {});
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** Plural helper: both languages take the same shape here. */
export const plural = (count, one, many) => (count === 1 ? one : many);

